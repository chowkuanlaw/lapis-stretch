// Render the desktop's mascot drawings into static PNGs for React Native.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const sharp = require('sharp');
const { KUIH, EX } = require('../../renderer/data.js');

const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.resolve(__dirname, '../../renderer/mascot.js'), 'utf8'), context);
const destination = path.resolve(__dirname, '../assets/kuih');
fs.mkdirSync(destination, { recursive: true });

const css = `<style>
  .limb{fill:none;stroke:#2A1F1A;stroke-width:4.5;stroke-linecap:round;stroke-linejoin:round}
  .hand,.foot,.eye{fill:#2A1F1A}
  .outline{fill:none;stroke:#2A1F1A;stroke-width:3.5}
  .line{fill:none;stroke:#2A1F1A;stroke-width:2.6;stroke-linecap:round}
  .blush{fill:#F58FAE;opacity:.85}
  .fx{fill:none;stroke:#C9184A;stroke-width:3.5;stroke-linecap:round;stroke-linejoin:round}
  .dash{stroke-dasharray:3 6}
  .zz{font-family:sans-serif;font-weight:800;font-size:18px;fill:#4FA34A}
  .stk *{fill:#FFFDF6!important;stroke:#FFFDF6!important;stroke-width:13px;stroke-linejoin:round;stroke-linecap:round;stroke-dasharray:none!important}
</style>`;

(async () => {
  const lines = ['// Generated by scripts/generate-kuih.cjs. Do not edit by hand.', 'export const mascots: Record<string, number> = {'];
  const poses = ['idle', ...EX.map(e => e.pose)];
  for (const kuih of KUIH) {
    for (const pose of poses) {
      const name = `${kuih.id}-${pose}`;
      let svg = context.window.lapisSVG(pose, kuih.name, false, kuih.id);
      svg = svg.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ');
      svg = svg.replace(/(<svg[^>]*>)/, `$1${css}`);
      await sharp(Buffer.from(svg), { density: 220 }).resize(288, 352).png().toFile(path.join(destination, `${name}.png`));
      lines.push(`  '${name}': require('../assets/kuih/${name}.png'),`);
    }
  }
  lines.push('};', '');
  fs.writeFileSync(path.resolve(__dirname, '../src/mascots.ts'), lines.join('\n'));
  console.log(`Generated ${KUIH.length * poses.length} mascot images`);
})().catch(error => { console.error(error); process.exitCode = 1; });
